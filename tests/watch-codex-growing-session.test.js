const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
test('growing old session still delivers completion when Windows mtime is unchanged',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'notify-stale-mtime-'));
  const keys=['HOME','USERPROFILE','CODEX_WATCH_BACKEND','CODEX_FOLLOW_TOP_N','CODEX_SEED_CATCHUP_MS','CODEX_TUI_LOG_PATH'];
  const saved=Object.fromEntries(keys.map(k=>[k,process.env[k]]));
  Object.assign(process.env,{HOME:dir,USERPROFILE:dir,CODEX_WATCH_BACKEND:'sessions',CODEX_FOLLOW_TOP_N:'1',CODEX_SEED_CATCHUP_MS:'30000',CODEX_TUI_LOG_PATH:path.join(dir,'none.log')});
  const enginePath=require.resolve('../src/engine'),watchPath=require.resolve('../src/watch');
  const oldEngine=require.cache[enginePath],oldWatch=require.cache[watchPath];
  const sent=[];const logs=[];
  require.cache[enginePath]={id:enginePath,filename:enginePath,loaded:true,exports:{sendNotifications:async args=>{sent.push(args);return {results:[{ok:true}]};}}};
  delete require.cache[watchPath];
  const sessions=path.join(dir,'.codex/sessions');fs.mkdirSync(sessions,{recursive:true});
  const file=path.join(sessions,'old-chat.jsonl');fs.writeFileSync(file,'');
  const oldDate=new Date(Date.now()-3600000);fs.utimesSync(file,oldDate,oldDate);
  const stop=require('../src/watch').startWatch({sources:['codex'],intervalMs:50,confirmAlert:{enabled:true},log:l=>logs.push(l)});
  t.after(()=>{stop();for(const[k,v]of Object.entries(saved)){if(v==null)delete process.env[k];else process.env[k]=v;}if(oldEngine)require.cache[enginePath]=oldEngine;else delete require.cache[enginePath];if(oldWatch)require.cache[watchPath]=oldWatch;else delete require.cache[watchPath];fs.rmSync(dir,{recursive:true,force:true});});
  await sleep(650);
  fs.writeFileSync(path.join(sessions,'new-chat.jsonl'),JSON.stringify({timestamp:new Date().toISOString(),type:'session_meta',payload:{id:'new-chat',source:'cli'}})+'\n');
  await sleep(650);
  const append=(type,payload)=>{fs.appendFileSync(file,JSON.stringify({timestamp:new Date().toISOString(),type,payload})+'\n');fs.utimesSync(file,oldDate,oldDate);};
  append('session_meta',{id:'old-chat',source:'cli'});
  append('event_msg',{type:'task_started',turn_id:'old-chat-turn'});
  append('event_msg',{type:'task_complete',turn_id:'old-chat-turn',last_agent_message:'old chat finished'});
  await sleep(1500);
  assert.equal(sent.length,1,logs.join('\n'));
  assert.equal(sent[0].outputContent,'old chat finished');
  append('event_msg',{type:'task_started',turn_id:'old-chat-question'});
  append('response_item',{type:'function_call',name:'request_user_input_async',call_id:'stale-question',arguments:JSON.stringify({questions:[{title:'old chat needs input'}]})});
  await sleep(1000);
  assert.equal(sent.length,2,logs.join('\n'));
  assert.equal(sent[1].notifyKind,'confirm');
});
